tasks.register("copyApkToRoot") {
    doNotTrackState("Avoid hashing OneDrive directory")
    doLast {
        val src = layout.buildDirectory.file("outputs/apk/debug/app-debug.apk").get().asFile
        val dest = File(rootProject.projectDir, "app-debug.apk")
        if (src.exists()) {
            src.copyTo(dest, overwrite = true)
        }
    }
}

afterEvaluate {
    tasks.findByName("assembleDebug")?.finalizedBy("copyApkToRoot")
}
